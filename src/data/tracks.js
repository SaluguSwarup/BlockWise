/** Health band helper used by the visualiser and every health chip. */
export function healthBand(health) {
  if (health < HEALTH_CRITICAL_THRESHOLD) return 'critical';
  if (health < HEALTH_THRESHOLD) return 'warning';
  return 'healthy';
}

export function healthLabel(health) {
  const band = healthBand(health);
  return band === 'critical' ? 'CRITICAL' : band === 'warning' ? 'DEGRADED' : 'HEALTHY';
}

